    private final boolean[][] pixels;

    Icon(String... rows) {
        pixels = new boolean[rows.length][];
        for (int y = 0; y < rows.length; y++) {
            pixels[y] = new boolean[rows[y].length()];
            for (int x = 0; x < rows[y].length(); x++) pixels[y][x] = rows[y].charAt(x) == '#';
        }
    }

    public static final int SIZE = 9;

    public void draw(Canvas c, int x, int y, int color) {
        for (int py = 0; py < pixels.length; py++) {
            boolean[] row = pixels[py];
            int run = -1;
            for (int px = 0; px <= row.length; px++) {
                boolean on = px < row.length && row[px];
                if (on && run < 0) run = px;
                if (!on && run >= 0) {
                    c.fill(x + run, y + py, px - run, 1, color);
                    run = -1;
                }
            }
        }
    }
