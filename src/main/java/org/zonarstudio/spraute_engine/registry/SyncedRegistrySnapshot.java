    private static void appendParticle(StringBuilder sb, CustomParticleRegistry.CustomParticleDef def) {
        if (def == null || def.id == null || def.id.isBlank()) return;
        sb.append("create particle ").append(def.id).append(" {\n");
        str(sb, "texture", def.texture);
        sb.append("}\n\n");
    }

