    private static void appendTab(StringBuilder sb, CustomBlockRegistry.CustomTabDef tab) {
        if (tab == null || tab.id == null || tab.id.isBlank()) return;
        sb.append("create tab ").append(tab.id).append(" {\n");
        String name = CustomBlockRegistry.TAB_DISPLAY_NAMES.get(tab.id);
        if (name != null && !name.isBlank()) {
            sb.append("    name = \"").append(escape(name)).append("\"\n");
        }
        if (tab.icon != null && !tab.icon.isBlank()) {
            sb.append("    icon = \"").append(escape(tab.icon)).append("\"\n");
        }
        if (!tab.extraItems.isEmpty()) {
            sb.append("    items = [");
            for (int i = 0; i < tab.extraItems.size(); i++) {
                if (i > 0) sb.append(", ");
                sb.append('"').append(escape(tab.extraItems.get(i))).append('"');
            }
            sb.append("]\n");
        }
        sb.append("}\n\n");
    }
